export GPU_MEMORY_UTILIZATION="${GPU_MEMORY_UTILIZATION:-0.40}"
export KV_CACHE_MEMORY_BYTES="${KV_CACHE_MEMORY_BYTES:-256M}"
export QUANTIZATION="${QUANTIZATION:-bitsandbytes}"
